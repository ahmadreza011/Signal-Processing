double* FIRfilter(double h[],double sine[] ) {      // or (double* h, double* sine)
    double *output = (double*) malloc((N + H - 1) * sizeof(double));
    for(int i = 0; i < N + H -1; i++) {
        output[i] = 0;
    }
    for(int n = 0; n < N + H - 1; n++) {
        for(int i = 0; i < N; i++) {
            if((n - i) >= 0 && (n - i) < H ) {
                if(sine[i] != 0 && h[n-i] != 0) {    
                    output[n] = output[n] + (sine[i] * h[n-i]);
                }
            }
        }
    }
    return output;
}

